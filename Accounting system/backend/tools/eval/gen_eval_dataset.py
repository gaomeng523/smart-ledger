EXPENSE_TPL = ["{p} {a}", "{p}花了{a}块", "{p}，{a}元，{ch}付的", "{d}{p}{a}元"]
INCOME_TPL = ["{p} {a}", "{p}到账{a}", "{d}{p}{a}元", "{p}，{a}元，{ch}到账"]
DATES = ["今天", "昨天", "11月10日", "前天"]
CHANNELS = ["微信", "支付宝", "现金", "银行卡"]


def num(value):
    return str(int(value)) if float(value).is_integer() else str(value)


def build():
    bank, test = [], []
    for code, (bill_type, phrases, amounts) in CATS.items():
        for i in range(4):
            template = (INCOME_TPL if bill_type == 1 else EXPENSE_TPL)[i]
            text = template.format(p=phrases[i], a=num(amounts[i]),
                                   ch=random.choice(CHANNELS), d=random.choice(DATES))
            item = {"text": text, "amount": amounts[i], "categoryCode": code, "billType": bill_type}
            (bank if i in (0, 2) else test).append(item)
    return bank, test


